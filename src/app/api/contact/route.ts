import { NextResponse } from 'next/server'
import { z } from 'zod'
import { db } from '@/lib/db'

/**
 * POST /api/contact
 * Contract: { name, email, message } → 201 { ok: true, id }
 *           | 400 { error } (invalid JSON / validation)
 *           | 429 { error } (rate limited)
 *           | 500 { error } (unexpected internal error — details never leaked)
 */

const contactSchema = z.object({
  name: z.string().trim().min(2).max(120),
  email: z.string().trim().email().max(200),
  message: z.string().trim().min(10).max(4000),
})

// Lightweight in-memory rate limit: max 5 requests per 10 minutes per client IP
// (module-scope Map — fine for a single server process; resets on redeploy).
const RATE_LIMIT_MAX = 5
const RATE_LIMIT_WINDOW_MS = 10 * 60 * 1000

const rateLimitMap = new Map<string, { count: number; resetAt: number }>()

function isRateLimited(key: string): boolean {
  const now = Date.now()
  const entry = rateLimitMap.get(key)

  if (!entry || now >= entry.resetAt) {
    // Periodically sweep expired entries so the Map cannot grow unbounded.
    if (rateLimitMap.size > 1000) {
      for (const [k, v] of rateLimitMap) {
        if (now >= v.resetAt) rateLimitMap.delete(k)
      }
    }
    rateLimitMap.set(key, { count: 1, resetAt: now + RATE_LIMIT_WINDOW_MS })
    return false
  }

  entry.count += 1
  return entry.count > RATE_LIMIT_MAX
}

export async function POST(request: Request) {
  // Rate limit first (cheap rejection before any parsing/DB work).
  const clientKey =
    request.headers.get('x-forwarded-for')?.split(',')[0]?.trim() || 'unknown'
  if (isRateLimited(clientKey)) {
    return NextResponse.json(
      { error: 'Too many requests. Try again later.' },
      { status: 429 },
    )
  }

  // Parse JSON body safely.
  let body: unknown
  try {
    body = await request.json()
  } catch {
    return NextResponse.json({ error: 'Invalid JSON' }, { status: 400 })
  }

  // Validate.
  const parsed = contactSchema.safeParse(body)
  if (!parsed.success) {
    return NextResponse.json(
      { error: parsed.error.issues[0]?.message ?? 'Invalid input' },
      { status: 400 },
    )
  }

  // Persist (only server-derived fields; ids/dates are generated by Prisma).
  try {
    const submission = await db.contactSubmission.create({
      data: {
        name: parsed.data.name,
        email: parsed.data.email,
        message: parsed.data.message,
      },
    })
    return NextResponse.json({ ok: true, id: submission.id }, { status: 201 })
  } catch (error) {
    console.error('[api/contact] Failed to save contact submission:', error)
    return NextResponse.json({ error: 'Internal error' }, { status: 500 })
  }
}

