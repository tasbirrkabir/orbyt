import { NextResponse } from 'next/server'
import { z } from 'zod'
import { getServerSession } from 'next-auth/next'
import { authOptions, type SessionUserWithId } from '@/lib/auth'
import { db } from '@/lib/db'
import { checkRateLimit, clientIp } from '@/lib/rate-limit'
import { sendLeadReceivedEmail } from '@/lib/email'

/**
 * POST /api/contact
 * Contract: { name, email, message, topic? } -> 201 { ok: true, id }
 *           | 400 { error } (invalid JSON / validation)
 *           | 429 { error } (rate limited)
 *           | 500 { error } (unexpected internal error, details never leaked)
 *
 * Guest submissions are accepted (userId null). When a session exists, the
 * submission is linked to the account via userId. `topic` is stored as the
 * client sent it (any label, e.g. "Something else"), capped at 80 chars.
 */

const contactSchema = z.object({
  name: z.string().trim().min(2).max(120),
  email: z.string().trim().email().max(200),
  message: z.string().trim().min(10).max(4000),
  topic: z
    .string()
    .trim()
    .max(80)
    .optional()
    .transform((t) => (t && t.length > 0 ? t : null)),
})

// Shared limiter (src/lib/rate-limit.ts): max 5 requests per 10 minutes
// per client IP. Verified Task 14-b: requests 1..5 -> 201, request 6 in
// the window -> 429.

export async function POST(request: Request) {
  // Rate limit first (cheap rejection before any parsing/DB work).
  if (!checkRateLimit('contact', clientIp(request), 5, 10 * 60 * 1000).ok) {
    return NextResponse.json(
      { error: 'Too many requests. Try again later.' },
      { status: 429 },
    )
  }

  // Parse JSON body safely.
  let body: unknown
  try {
    body = await request.json()
  } catch {
    return NextResponse.json({ error: 'Invalid JSON' }, { status: 400 })
  }

  // Validate.
  const parsed = contactSchema.safeParse(body)
  if (!parsed.success) {
    return NextResponse.json(
      { error: parsed.error.issues[0]?.message ?? 'Invalid input' },
      { status: 400 },
    )
  }

  // Persist (only server-derived fields; ids/dates are generated by Prisma).
  try {
    // Link the submission to the account when a session exists (guests stay null).
    const session = await getServerSession(authOptions)
    const sessionUser = session?.user as SessionUserWithId | undefined
    const userId =
      sessionUser && typeof sessionUser.id === 'string' ? sessionUser.id : null

    const submission = await db.contactSubmission.create({
      data: {
        name: parsed.data.name,
        email: parsed.data.email,
        message: parsed.data.message,
        topic: parsed.data.topic,
        userId,
      },
    })

    // Lead lifecycle starts here: every submission is a lead with
    // status NEW (schema default). The auto-reply goes through the
    // EmailService (outbox row first, console provider in dev), so
    // the contact path stays fast and a provider failure cannot
    // break the visitor's submission.
    sendLeadReceivedEmail(parsed.data.email, parsed.data.name)

    return NextResponse.json({ ok: true, id: submission.id }, { status: 201 })
  } catch (error) {
    console.error('[api/contact] Failed to save contact submission:', error)
    return NextResponse.json({ error: 'Internal error' }, { status: 500 })
  }
}
